"""Every tick a screen or an endpoint names is one the Roles screen can grant.

A tick named in code but missing from permission_tree.json can never be given to
a role: the screen it guards is owner-only by accident. These tests read the
source, so a new tab or endpoint that names a tick the tree does not offer
fails the build instead of reaching a user.
"""

import glob
import os
import re

from django.test import TestCase

from pos_backend.permission_tree import load_tree, module_aliases, offered_verbs, submodule_aliases

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FRONTEND_APP = os.path.join(os.path.dirname(BACKEND), 'frontend', 'src', 'app')


def ticks():
    return {m['key']: {s['key'] for s in m['submodules']} for m in load_tree()['modules']}


def known(module, sub):
    """True if module > sub is a tick, directly or through a legacy alias."""
    tree = ticks()
    module = module_aliases()[0].get(module, module)
    if sub in tree.get(module, ()):
        return True
    return sub in (submodule_aliases().get(module) or {})


class FrontendNamesRealTicks(TestCase):
    # `permissions.billing?.access` is the old shape, kept only to explain the bug it caused.
    SKIP = ('module-access.ts', 'module-access.spec.ts')
    PATTERN = re.compile(r'permissions\??\.(\w+)\??\.(\w+)')

    def test_every_permission_the_screens_check_is_in_the_tree(self):
        if not os.path.isdir(FRONTEND_APP):
            self.skipTest('frontend source not present')
        wrong = []
        for path in glob.glob(os.path.join(FRONTEND_APP, '**', '*'), recursive=True):
            if not path.endswith(('.ts', '.html')) or os.path.basename(path) in self.SKIP:
                continue
            if 'node_modules' in path or os.sep + '_original' in path or path.endswith('.spec.ts'):
                continue
            with open(path, encoding='utf-8', errors='ignore') as handle:
                text = handle.read()
            for module, sub in self.PATTERN.findall(text):
                if sub in ('all_centers',) or module in ('all_centers',):
                    continue
                if not known(module, sub):
                    wrong.append(f'{os.path.relpath(path, FRONTEND_APP)}: permissions.{module}.{sub}')
        self.assertEqual(wrong, [], 'A screen checks a tick the Roles screen cannot grant:\n' + '\n'.join(wrong))


class ActionTicksReachTheScreens(TestCase):
    """A button behind an action tick must be hidden without it, not left to fail with a 403.

    Every action tick in the tree is named somewhere in the frontend, except the
    few that have no button in the web app at all."""

    NO_BUTTON = {
        'set_app_pin': 'the staff app PIN is set from the mobile app / API, the web form has no field for it',
        'generate': 'payrolls are generated by the API, the Payrolls tab has no Generate button',
        'unlock': 'the Payrolls tab has no Unlock button',
        'amend_closing': 'amending a closing is submitting it again; the server refuses it with a clear message',
    }

    def test_every_action_tick_is_checked_by_a_screen(self):
        if not os.path.isdir(FRONTEND_APP):
            self.skipTest('frontend source not present')
        text = ''
        for path in glob.glob(os.path.join(FRONTEND_APP, '**', '*'), recursive=True):
            if path.endswith(('.ts', '.html')) and not path.endswith('.spec.ts') and 'permission-tree' not in path \
                    and os.sep + '_original' not in path and 'node_modules' not in path:
                with open(path, encoding='utf-8', errors='ignore') as handle:
                    text += handle.read()
        missing = []
        for module in load_tree()['modules']:
            for sub in module['submodules']:
                for action in sub.get('actions', ()):
                    key = action['key']
                    if key in self.NO_BUTTON:
                        continue
                    if not re.search(r"['\"\.]%s\b" % re.escape(key), text):
                        missing.append(f"{module['key']}.{sub['key']}.{key}")
        self.assertEqual(missing, [], 'These action ticks are never checked by a screen, so its button shows '
                                      'to people who cannot use it:\n' + '\n'.join(missing))


class BackendNamesRealTicks(TestCase):
    MODULE = re.compile(r"permission_module\s*=\s*'(\w+)'")
    SUBMODULE = re.compile(r"permission_submodule\s*=\s*'(\w+)'")
    ACTION_SUBS = re.compile(r"permission_action_submodules\s*=\s*\{([^}]*)\}", re.S)
    ACTION_TICKS = re.compile(r"permission_action_ticks\s*=\s*\{([^}]*)\}", re.S)

    def classes(self):
        for path in glob.glob(os.path.join(BACKEND, '**', '*.py'), recursive=True):
            rel = os.path.relpath(path, BACKEND)
            if rel.startswith(('venv', 'migrations')) or '/tests' in rel.replace(os.sep, '/') or os.path.basename(path).startswith('tests'):
                continue
            if rel.replace(os.sep, '/') == 'pos_backend/permissions.py':
                continue            # its docstring shows an example of each setting
            with open(path, encoding='utf-8', errors='ignore') as handle:
                text = handle.read()
            for block in re.split(r'\nclass ', text)[1:]:
                yield rel, block

    def test_every_declared_tick_exists(self):
        wrong = []
        for rel, block in self.classes():
            module = self.MODULE.search(block)
            if not module:
                continue
            module = module.group(1)
            sub = self.SUBMODULE.search(block)
            if sub and not known(module, sub.group(1)):
                wrong.append(f'{rel}: {module}.{sub.group(1)}')
            for found in self.ACTION_SUBS.findall(block):
                for target in re.findall(r":\s*'(\w+)'", found):
                    if not known(module, target):
                        wrong.append(f'{rel}: action submodule {module}.{target}')
            for found in self.ACTION_TICKS.findall(block):
                for target in re.findall(r"\(\s*'(\w+)'\s*,\s*'(\w+)'\s*\)", found):
                    if not known(module, target[0]):
                        wrong.append(f'{rel}: action tick {module}.{target[0]}')
        self.assertEqual(wrong, [], 'An endpoint is guarded by a tick the Roles screen cannot grant:\n' + '\n'.join(wrong))


class StockRequestTicks(TestCase):
    def test_the_stock_request_ticks_exist_in_the_inventory_module(self):
        for sub in ('stock_requests', 'approve_stock_requests', 'fulfill_stock_requests', 'stock_transfers'):
            self.assertTrue(known('inventory', sub), sub)

    def test_approving_and_sending_offer_only_view_and_edit(self):
        """Add and Delete mean nothing for an approval, so the Roles screen must not offer them."""
        verbs = offered_verbs()
        for sub in ('approve_stock_requests', 'fulfill_stock_requests'):
            self.assertEqual(sorted(verbs[('inventory', sub)]), ['read', 'update'], sub)
